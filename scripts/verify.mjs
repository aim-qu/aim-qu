import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
import {chromium} from 'playwright';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const out=path.join(root,'output');fs.mkdirSync(out,{recursive:true});
const server=JSON.parse(fs.readFileSync(path.join(root,'preview','server.json'),'utf8'));
const url=`http://127.0.0.1:${server.port}`;
const channel=fs.existsSync('C:/Program Files/Google/Chrome/Application/chrome.exe')?'chrome':'msedge';
const browser=await chromium.launch({channel});
try{
  const page=await browser.newPage({viewport:{width:1377,height:1100},reducedMotion:'reduce'});
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto(url,{waitUntil:'networkidle'});
  const article=page.locator('article.markdown-body');
  await page.waitForFunction(()=>[...document.querySelectorAll('article img')].every(img=>img.complete&&img.naturalWidth>0));
  assert.equal(await article.locator('script,style,iframe').count(),0);
  assert.equal(await article.locator('details').count(),2);
  const reduceSource=await article.locator('picture img').first().evaluate(img=>img.currentSrc);
  assert((await article.locator('picture img').evaluateAll(nodes=>nodes.map(img=>img.currentSrc))).every(src=>src.endsWith('.png')));
  assert(reduceSource.endsWith('rain-still.png'),reduceSource);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.screenshot({path:path.join(out,'profile-preview.png'),fullPage:true});
  await article.locator('details').nth(0).locator('summary').click();
  assert(await article.locator('details').nth(0).evaluate(e=>e.open));
  assert.match(await article.locator('details').nth(0).innerText(),/Rain Beat/);
  await article.locator('details').nth(1).locator('summary').click();
  assert(await article.locator('details').nth(1).evaluate(e=>e.open));
  await page.screenshot({path:path.join(out,'profile-expanded.png'),fullPage:true});
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.waitForFunction(()=>document.querySelector('picture img').currentSrc.endsWith('rain.gif'));
  const animatedSource=await article.locator('picture img').first().evaluate(img=>img.currentSrc);
  assert((await article.locator('picture img').evaluateAll(nodes=>nodes.map(img=>img.currentSrc))).every(src=>src.endsWith('.gif')));
  await page.setViewportSize({width:390,height:844});
  await page.emulateMedia({reducedMotion:'reduce'});
  await article.locator('details').nth(0).locator('summary').click();await article.locator('details').nth(1).locator('summary').click();
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.screenshot({path:path.join(out,'profile-mobile.png'),fullPage:true});
  const readme=fs.readFileSync(path.join(root,'README.md'),'utf8');
  for(const item of [...readme.matchAll(/(?:src|srcset|href)="\.\/(assets\/[^"#]+)"/g)])assert(fs.existsSync(path.join(root,item[1])),item[1]);
  assert(!/genka|q.?worxs|sample_db|company|contributions|streak|shields\.io|github-readme-stats/i.test(readme));
  assert(!/\bQu\b|\bQ\b|const qu\b/.test(readme));
  assert.equal(await article.locator('img[alt$="の動作デモ"]').count(),9);
  assert.equal(await article.locator('picture').count(),10);
  assert.deepEqual(errors,[]);
  const result={passed:true,renderer:server.renderer,url,reduceSource,animatedSource,checks:['GitHub-rendered Markdown','all images loaded','nine scene previews','two working disclosures','static image for reduced motion','animated GIF for normal motion','desktop and mobile without horizontal overflow','local image links exist','no company project claims'],errors};
  fs.writeFileSync(path.join(out,'verification.json'),JSON.stringify(result,null,2));console.log(JSON.stringify(result,null,2));
}finally{await browser.close();}
